@app.route("/api/analyze", methods=["POST"])
def analyze_dataset():
    """
    Upload and analyze dataset endpoint.
    Accepts:
      - Multipart CSV file (key: 'file')
      - Direct JSON array of account objects
    """
    try:
        pipeline = load_prediction_model()

        # Handle CSV File Upload
        if "file" in request.files:
            uploaded_file = request.files["file"]
            if uploaded_file.filename == "":
                return jsonify({"status": "error", "message": "No file was selected for upload."}), 400

            if not allowed_file(uploaded_file.filename):
                return jsonify({
                    "status": "error",
                    "message": "Invalid file format. Only .csv files are supported."
                }), 400

            try:
                # Read CSV into memory safely
                stream = io.StringIO(uploaded_file.stream.read().decode("utf-8-sig", errors="replace"))
                df = pd.read_csv(stream)
            except Exception as e:
                return jsonify({
                    "status": "error",
                    "message": f"Could not parse CSV file. Please ensure it is a valid CSV. Details: {str(e)}"
                }), 400

        # Handle Direct JSON Payload
        elif request.is_json:
            json_data = request.get_json()
            if not json_data:
                return jsonify({"status": "error", "message": "JSON body is empty."}), 400
            
            # Support either a list of accounts or {'accounts': [...]}
            if isinstance(json_data, dict) and "accounts" in json_data:
                records = json_data["accounts"]
            elif isinstance(json_data, list):
                records = json_data
            else:
                records = [json_data]
            
            df = pd.DataFrame(records)
        else:
            return jsonify({
                "status": "error",
                "message": "No CSV file or JSON data provided in request."
            }), 400

        # Validate and preprocess
        try:
            df = validate_and_preprocess_dataframe(df)
        except ValueError as ve:
            return jsonify({"status": "error", "message": str(ve)}), 400

        # Prepare model input (strictly the 9 numeric features; username excluded)
        X = df[MODEL_FEATURES]

        # Generate suspicious-class probability estimates
        # Class 1 is 'Suspicious/Fake'
        probabilities = pipeline.predict_proba(X)[:, 1]

        # Construct structured response
        results = []
        low_count = 0
        med_count = 0
        high_count = 0

        for idx, row in df.iterrows():
            prob = float(probabilities[idx])
            category = classify_risk(prob)
            warnings = compute_warning_indicators(row)

            if category == "Low Risk":
                low_count += 1
            elif category == "Medium Risk":
                med_count += 1
            else:
                high_count += 1

            record = {
                "username": str(row["username"]),
                "risk_score": round(prob, 4),
                "risk_percentage": f"{prob * 100:.1f}%",
                "risk_category": category,
                "warning_indicators": warnings,
                "features": {
                    feat: (int(row[feat]) if feat in ["has_profile_pic", "account_age_days", "followers_count", "following_count", "posts_count", "bio_length", "repetitive_comments"] else round(float(row[feat]), 2))
                    for feat in MODEL_FEATURES
                }
            }
            results.append(record)

        total_accounts = len(results)
        avg_score = round(float(np.mean(probabilities)), 4) if total_accounts > 0 else 0.0

        summary = {
            "total_accounts": total_accounts,
            "low_risk": low_count,
            "medium_risk": med_count,
            "high_risk": high_count,
            "average_risk_score": avg_score,
            "average_risk_percentage": f"{avg_score * 100:.1f}%"
        }

        return jsonify({
            "status": "success",
            "message": f"Successfully analyzed {total_accounts} account(s).",
            "summary": summary,
            "results": results
        }), 200

    except Exception as e:
        logger.exception("Unexpected error in /api/analyze")
        return jsonify({
            "status": "error",
            "message": f"Server processing error: {str(e)}"
        }), 500

@app.route("/api/export", methods=["POST"])
def export_results():
    """
    Generates a downloadable CSV report containing original account features,
    predicted risk score, risk category, and rule-based warning signals.
    """
    try:
        data = request.get_json(silent=True)
        if not data or "results" not in data or not data["results"]:
            return jsonify({"status": "error", "message": "No analysis results provided for export."}), 400

        results = data["results"]

        # Output CSV in memory
        output = io.StringIO()
        fieldnames = [
            "username",
            "account_age_days",
            "followers_count",
            "following_count",
            "posts_count",
            "avg_likes",
            "avg_comments",
            "has_profile_pic",
            "bio_length",
            "repetitive_comments",
            "risk_score",
            "risk_percentage",
            "risk_category",
            "warning_signals"
        ]
        writer = csv.DictWriter(output, fieldnames=fieldnames)
        writer.writeheader()

        for item in results:
            feats = item.get("features", {})
            warnings = " | ".join(item.get("warning_indicators", [])) or "None"
            row = {
                "username": item.get("username", "unknown"),
                "account_age_days": feats.get("account_age_days", 0),
                "followers_count": feats.get("followers_count", 0),
                "following_count": feats.get("following_count", 0),
                "posts_count": feats.get("posts_count", 0),
                "avg_likes": feats.get("avg_likes", 0),
                "avg_comments": feats.get("avg_comments", 0),
                "has_profile_pic": feats.get("has_profile_pic", 0),
                "bio_length": feats.get("bio_length", 0),
                "repetitive_comments": feats.get("repetitive_comments", 0),
                "risk_score": item.get("risk_score", 0),
                "risk_percentage": item.get("risk_percentage", "0%"),
                "risk_category": item.get("risk_category", "Unknown"),
                "warning_signals": warnings
            }
            writer.writerow(row)

        output.seek(0)
        return Response(
            output.getvalue(),
            mimetype="text/csv",
            headers={"Content-Disposition": "attachment; filename=fakeguard_ai_analysis_report.csv"}
        )

    except Exception as e:
        logger.exception("Error generating CSV export")
        return jsonify({"status": "error", "message": f"Export failed: {str(e)}"}), 500

